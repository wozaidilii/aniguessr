export function getTravelCopy(locale: PilgrimageLocale): Copy {
  return locale === "zh"
    ? zh
    : locale === "zh-tw"
      ? tw
      : locale === "ja"
        ? ja
        : en;
}
export function dayLabel(locale: PilgrimageLocale, day: number): string {
  return locale === "zh" || locale === "zh-tw" ? `第 ${day} 天` : `Day ${day}`;
}
